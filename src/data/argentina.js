/** Obtiene departamentos de una provincia, o [] si no hay datos */
export function getDepartamentos(provinciaId) {
  return departamentos[provinciaId] || []
}

/** Obtiene localidades de un departamento, o [] si no hay datos */
export function getLocalidades(departamentoId) {
  return localidades[departamentoId] || []
}

/** Nombre de provincia por id */
export function getNombreProvincia(id) {
  return provincias.find(p => p.id === id)?.nombre || id
}

/** Nombre de departamento por id */
export function getNombreDepartamento(provId, deptId) {
  return (departamentos[provId] || []).find(d => d.id === deptId)?.nombre || deptId
}
